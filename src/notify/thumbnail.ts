// ADR 0012: the app's own thumbnails for its hidden group and nudge log. Shared by both write guards (a PNG of at most
// 200 KB is the only thumbnail either may send) and loaded from this site's own origin as a Blob, never from elsewhere.
// Whether ArcGIS Online accepts a multipart `thumbnail` on createGroup and on the item update is UNVERIFIED (research
// docs/research/app-data-lifecycle.md, section 6). DC-122 switched it on, with a fallback: if ArcGIS refuses the request
// the group and the log retry once without the thumbnail, so a thumbnail problem never blocks either.

/** On (DC-122). A refused thumbnail is retried once without it by createGroup and by the log's title update. */
export const SEND_THUMBNAILS = true;

/** The largest thumbnail either guard allows (ArcGIS Online itself allows 10 MB; ours are tens of KB). */
export const MAX_THUMB_BYTES = 200_000;

/** Static assets under public/, generated by tools/make-app-thumbs.mjs. Group is 400x400, log is 600x400. */
export const THUMB_PATHS = { group: 'app-data/group-thumb.png', log: 'app-data/log-thumb.png' } as const;
export type ThumbKind = keyof typeof THUMB_PATHS;

/** A request parameter value: arcgis-rest-js sends a Blob (or File) as a multipart part. */
export type ParamValue = string | number | Blob;

/** True for a non-empty PNG Blob/File of at most MAX_THUMB_BYTES. */
export function isPngThumbnail(v: unknown): v is Blob {
  return typeof Blob !== 'undefined' && v instanceof Blob && v.type === 'image/png' && v.size > 0 && v.size <= MAX_THUMB_BYTES;
}

const PNG_SIGNATURE = [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a];

/** Resolves to the thumbnail, or null when it can't be had. A thumbnail is decoration: it never blocks creating anything. */
export type ThumbnailLoader = (kind: ThumbKind) => Promise<Blob | null>;

/**
 * Fetches a thumbnail from this site's own origin (a path under the site base, never an absolute URL) and checks that
 * the bytes really are a PNG within the size limit. A missing file or an HTML fallback page gives null.
 */
export function createThumbnailLoader(fetchFn: typeof fetch = (...a) => fetch(...a), base: string = import.meta.env?.BASE_URL ?? '/'): ThumbnailLoader {
  return async (kind) => {
    const url = `${base.replace(/\/*$/, '/')}${THUMB_PATHS[kind]}`;
    if (!url.startsWith('/') || url.startsWith('//')) return null; // same origin only
    try {
      const res = await fetchFn(url, { credentials: 'same-origin' });
      if (!res.ok) return null;
      const bytes = new Uint8Array(await res.arrayBuffer());
      if (!bytes.length || bytes.length > MAX_THUMB_BYTES || !PNG_SIGNATURE.every((b, i) => bytes[i] === b)) return null;
      return new File([bytes], 'thumbnail.png', { type: 'image/png' });
    } catch {
      return null;
    }
  };
}
